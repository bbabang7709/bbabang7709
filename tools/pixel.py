ADV = 6  # 글자 간격(폰트 픽셀 단위)


def text_width(text, scale=1):
    return (len(text) * ADV - 1) * scale


def text_cells(text, x, y, color, scale=1):
    cells = {}
    for i, ch in enumerate(text.upper()):
        glyph = FONT.get(ch, FONT["?"])
        for gy, row in enumerate(glyph):
            for gx, c in enumerate(row):
                if c == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            cells[(x + (i * ADV + gx) * scale + sx, y + gy * scale + sy)] = color
    return cells


# ---------------------------------------------------------------- 공용 처리
def outlined(cells, color=INK, diagonal=False):
    """셀 주변 1칸에 외곽선을 둘러서 반환."""
    out = {}
    dirs = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    if diagonal:
        dirs += [(1, 1), (-1, 1), (1, -1), (-1, -1)]
    for (x, y) in cells:
        for dx, dy in dirs:
            q = (x + dx, y + dy)
            if q not in cells:
                out[q] = color
    out.update(cells)
    return out


def shifted(cells, dx, dy):
    return {(x + dx, y + dy): c for (x, y), c in cells.items()}


def scaled(cells, s):
    out = {}
    for (x, y), c in cells.items():
        for sy in range(s):
            for sx in range(s):
                out[(x * s + sx, y * s + sy)] = c
    return out


def sprite(rows, palette, x=0, y=0):
    cells = {}
    for gy, row in enumerate(rows):
        for gx, ch in enumerate(row):
            if ch in palette:
                cells[(x + gx, y + gy)] = palette[ch]
    return cells


def rects(cells, unit, cls=None):
    """셀 사전을 가로로 이어 붙인 <rect>들로 변환 (파일 크기 절약)."""
    by_row = {}
    for (x, y), c in cells.items():
        by_row.setdefault(y, []).append((x, c))
    out = []
    for y in sorted(by_row):
        row = sorted(by_row[y])
        i = 0
        while i < len(row):
            x0, c = row[i]
            j = i
            while j + 1 < len(row) and row[j + 1][0] == row[j][0] + 1 and row[j + 1][1] == c:
                j += 1
            w = row[j][0] - x0 + 1
            out.append(f'<rect x="{x0 * unit}" y="{y * unit}" width="{w * unit}" height="{unit}" fill="{c}"/>')
            i = j + 1
    body = "".join(out)
    if cls:
        return f'<g class="{cls}">{body}</g>'
    return body


def frame(x0, y0, w, h, fill, border, outline=INK, notch=1):
    """도트 창 테두리: 바깥 외곽선 + 안쪽 밝은 테두리 + 채움, 모서리는 계단식."""
    cells = {}
    for y in range(y0, y0 + h):
        for x in range(x0, x0 + w):
            dx = min(x - x0, x0 + w - 1 - x)
            dy = min(y - y0, y0 + h - 1 - y)
            if dx + dy < notch:          # 모서리 깎기
                continue
            if dx == 0 or dy == 0 or dx + dy == notch:
                cells[(x, y)] = outline
            elif dx == 1 or dy == 1 or dx + dy == notch + 1:
                cells[(x, y)] = border
            else:
                cells[(x, y)] = fill
    return cells


